// ==========================================================
// ERMS - EMPLOYEE MODEL
// ==========================================================

const mongoose = require("mongoose");

const employeeSchema = new mongoose.Schema(
    {
        // --------------------------------------------------
        // EMPLOYEE ID
        // --------------------------------------------------
        employeeId: {
            type: String,
            unique: true,
            required: true,
            trim: true
        },

        // --------------------------------------------------
        // EMPLOYEE NAME
        // --------------------------------------------------
        name: {
            type: String,
            required: true,
            trim: true
        },

        // --------------------------------------------------
        // MOBILE
        // --------------------------------------------------
        mobile: {
            type: String,
            unique: true,
            required: true,
            trim: true
        },

        // --------------------------------------------------
        // FACE PHOTO
        // --------------------------------------------------
        facePhoto: {
            type: String,
            default: ""
        },

        // --------------------------------------------------
        // EMAIL
        // --------------------------------------------------
        email: {
            type: String,
            unique: true,
            required: true,
            trim: true,
            lowercase: true
        },

        // --------------------------------------------------
        // PASSWORD
        // --------------------------------------------------
        password: {
            type: String,
            required: true
        },

        // --------------------------------------------------
        // DEPARTMENT
        // --------------------------------------------------
        department: {
            type: String,
            default: "",
            trim: true
        },

        // --------------------------------------------------
        // POSITION
        // --------------------------------------------------
        position: {
            type: String,
            default: "",
            trim: true
        },

        // --------------------------------------------------
        // ROLE
        // --------------------------------------------------
        role: {
            type: String,
            default: "employee",
            trim: true
        },

        // --------------------------------------------------
        // SALARY
        // --------------------------------------------------
        salary: {
            type: Number,
            default: 0
        },

        // --------------------------------------------------
        // ATTENDANCE %
        // --------------------------------------------------
        attendance: {
            type: Number,
            default: 0
        },

        // --------------------------------------------------
        // LEAVE STATUS
        // --------------------------------------------------
        leaveStatus: {
            type: String,
            default: "Pending"
        }
    },
    {
        timestamps: true
    }
);

// ==========================================================
// EXPORT MODEL
// ==========================================================

module.exports =
    mongoose.models.Employee ||
    mongoose.model(
        "Employee",
        employeeSchema
    );